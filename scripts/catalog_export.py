#!/usr/bin/env python3
"""Deterministically export public carriers from data/methods.json.

Exports never import CSV/HTML edits into the authoritative registry. Rebuilding
does not advance the registry's evidence or review date.
"""
import csv
import io
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def json_string(value):
    # Script blocks must not be closable by a title/description from upstream.
    return json.dumps(value, ensure_ascii=False).replace('<', '\\u003c').replace('>', '\\u003e')


def load_abstracts(path):
    text = path.read_text(encoding='utf-8-sig')
    pattern = r'("(?:[^"\\]|\\.)*"):\s*\{\s*abstractEn:\s*("(?:[^"\\]|\\.)*")\s*,\s*abstractCn:\s*("(?:[^"\\]|\\.)*")\s*\}'
    return {json.loads(name): {'abstractEn': json.loads(en), 'abstractCn': json.loads(cn)}
            for name, en, cn in re.findall(pattern, text)}


def html_records(text):
    block = text.split('const METHODS = [', 1)[1].split('\n];', 1)[0]
    records = []
    for line in block.splitlines():
        line = line.strip().rstrip(',')
        if not line:
            continue
        quoted = re.sub(r'"(?:[^"\\]|\\.)*"|[a-zA-Z_]\w*(?=\s*:)',
                        lambda match: match[0] if match[0].startswith('"') else json.dumps(match[0]), line)
        records.append(json.loads(quoted))
    return records


def expected_html(row):
    venue = (row.get('venue') or 'arXiv').split()[0].rstrip(',')
    if venue.lower() in ('arxiv', 'arxiv.'):
        venue = 'arXiv'
    return {'name': row['name'], 'short': row['name'], 'cat': row['category'],
            'venue': venue, 'year': row.get('year') or 0, 'desc': row.get('desc', ''),
            'arxiv': row.get('arxiv_id', ''), 'citations': None,
            'paper_title': row.get('title', ''), 'aliases': row.get('aliases', []),
            'venue_full': row.get('venue', ''), 'code': row.get('code_url', ''),
            'metadata_status': row.get('evidence', {}).get('metadata', 'unreviewed')}


def render_catalog(data):
    methods = data['methods']
    lines = ['# 3DGS and Related Research Catalog', '',
             '<!-- Generated by scripts/catalog_export.py; edit data/methods.json. -->', '',
             f"Registry updated: {data['generated_at']}; records: {len(methods)}; categories: {len(data['categories'])}.", '',
             'Catalog inclusion is not independent verification. Metadata, method identity, venue, and result claims require separate evidence.', '',
             'See data/evidence-audit.json for coverage, dates, unresolved records, and verification limits.', '']
    for category in data['categories']:
        lines += ['### ' + category, '']
        for row in methods:
            if row['category'] != category:
                continue
            aid = row.get('arxiv_id', '')
            link = f' [arXiv:{aid}](https://arxiv.org/abs/{aid})' if aid else ' [no arXiv ID; verify primary source]'
            lines.append(f"- **{row['name']}**{link} ({row.get('venue', '')}) — {row.get('desc', '')}")
        lines.append('')
    return '\n'.join(lines)


def export(root=ROOT, check=False):
    data_path = root / 'data/methods.json'
    data = json.loads(data_path.read_text(encoding='utf-8-sig'))
    methods = data['methods']
    counts = dict(Counter(row['category'] for row in methods))
    if data.get('count') != len(methods) or data.get('categories') != counts or data.get('category_count') != len(counts):
        raise ValueError('Registry counts disagree with records; repair the registry explicitly before exporting.')
    abstracts = load_abstracts(root / 'docs/abstracts.js')
    cache_path = root / '.arxiv_cache.json'
    cache = json.loads(cache_path.read_text(encoding='utf-8-sig')) if cache_path.exists() else {}
    csv_buffer = io.StringIO()
    writer = csv.writer(csv_buffer, lineterminator='\n')
    writer.writerow(['method', 'arxiv_id', 'venue', 'year', 'category', 'core_innovation', 'code_url'])
    for row in methods:
        writer.writerow([row['name'], row.get('arxiv_id', ''), row.get('venue', ''), row.get('year') or '',
                         row['category'], row.get('desc', ''), row.get('code_url', '')])
    ab_lines = ['const ABSTRACTS = {']
    for row in methods:
        ab = abstracts.get(row['name'], {'abstractEn': '', 'abstractCn': ''}).copy()
        metadata = cache.get(row.get('arxiv_id', ''), {})
        # Only freshly retrieved primary metadata can replace the English abstract.
        if metadata.get('retrieved_at') and metadata.get('summary'):
            ab['abstractEn'] = metadata['summary']
        ab_lines.append(f"  {json_string(row['name'])}: {{ abstractEn: {json_string(ab['abstractEn'])}, abstractCn: {json_string(ab['abstractCn'])} }},")
    ab_lines.append('};')
    html_path = root / 'docs/methods.html'
    html = html_path.read_text(encoding='utf-8-sig')
    head, remainder = html.split('const METHODS = [', 1)
    _, tail = remainder.split('\n];', 1)
    rows = []
    for row in methods:
        obj = expected_html(row)
        rows.append('  { ' + ', '.join(f'{key}: {json_string(value)}' for key, value in obj.items()) + ' },')
    catalog = render_catalog(data)
    taxonomy = {'generated_at': data['generated_at'], 'canonical': list(data['categories']), 'counts': counts}
    stats = {'generated_at': data['generated_at'], 'methods': len(methods), 'categories': len(counts),
             'with_arxiv': sum(bool(row.get('arxiv_id')) for row in methods),
             'with_code': sum(bool(row.get('code_url')) for row in methods),
             'skills': sum((folder / 'SKILL.md').is_file() for folder in (root / 'skills').iterdir()),
             'evidence_note': 'Record count is not the count of fully verified papers.'}
    rendered_html = head + 'const METHODS = [\n' + '\n'.join(rows) + '\n];' + tail
    code_map = {row['name']: row['code_url'] for row in methods if row.get('code_url')}
    if 'const CODE_MAP = {' in rendered_html:
        code_lines = ['const CODE_MAP = {'] + [f'  {json_string(key)}: {json_string(value)},' for key,value in code_map.items()] + ['};']
        rendered_html = re.sub(r'const CODE_MAP = \{.*?\n\};', lambda _: '\n'.join(code_lines), rendered_html, count=1, flags=re.S)
    outputs = {'3dgs-methods-overview.csv': csv_buffer.getvalue(),
        'docs/abstracts.js': '\n'.join(ab_lines) + '\n',
        'docs/methods.html': rendered_html,
        'data/categories.json': json.dumps(taxonomy, ensure_ascii=False, indent=1) + '\n',
        'data/catalog-stats.json': json.dumps(stats, ensure_ascii=False, indent=2) + '\n',
        '3dgs-methods-overview.md': catalog,
        'references/3dgs-methods-overview.md': catalog,
        'agent-router/references/3dgs-methods-overview.md': catalog}
    for file in (root / 'references').iterdir():
        if file.is_file() and file.suffix == '.md' and file.name != '3dgs-methods-overview.md':
            outputs['agent-router/references/' + file.name] = file.read_text(encoding='utf-8-sig')
    mismatches = []
    for relative, content in outputs.items():
        path = root / relative
        if not path.exists() or path.read_text(encoding='utf-8-sig') != content:
            mismatches.append(relative)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding='utf-8', newline='\n')
    return mismatches


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    changed = export(check=args.check)
    print(json.dumps({'mode': 'check' if args.check else 'export', 'different': changed}, ensure_ascii=False))
    raise SystemExit(1 if args.check and changed else 0)
